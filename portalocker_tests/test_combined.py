def test_combine_uses_sys_executable(tmp_path, monkeypatch):
    """B6: the combined-file smoke run must use ``sys.executable``.

    Hardcoding ``python3`` breaks on Windows venvs (no ``python3.exe``).
    """
    calls: list[list[str]] = []

    def spy(cmd, *args, **kwargs):
        calls.append(list(cmd))
        return subprocess.CompletedProcess(cmd, 0)

    monkeypatch.setattr(subprocess, 'run', spy)
    output_file = tmp_path / 'combined.py'
    __main__.main(['combine', '--output-file', str(output_file)])

    assert [sys.executable, str(output_file)] in calls


def test_combined(tmpdir):
    output_file = tmpdir.join('combined.py')
    __main__.main(['combine', '--output-file', output_file.strpath])

    print(output_file)  # noqa: T201
    print('#################')  # noqa: T201
    print(output_file.read())  # noqa: T201
    print('#################')  # noqa: T201

    sys.path.append(output_file.dirname)
    # The `combined` module is generated by the `combine` call above, so
    # static analysis can't resolve it; import it dynamically instead.
    combined = importlib.import_module('combined')

    assert hasattr(combined, 'lock')


def test_build_extra_creates_versioned_dist():
    """``build_extra.py`` must work with the path-based ``combine`` interface.

    The release script runs ``build_extra.py`` to emit the versioned single
    file. It used to hand ``combine()`` an open file object; after ``combine``
    switched to a ``pathlib.Path`` ``output_file`` (mkdir/open on it) that
    crashed with ``AttributeError``. Exercise the script exactly as the
    release flow does and assert the versioned dist file is produced.
    """
    from portalocker import __about__

    dist_file = __main__.dist_path / f'portalocker-{__about__.__version__}.py'
    pre_existing = dist_file.exists()
    try:
        result = subprocess.run(
            [sys.executable, 'build_extra.py'],
            cwd=__main__.base_path,
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, result.stderr
        assert dist_file.exists(), (
            f'{dist_file} was not created\n{result.stdout}\n{result.stderr}'
        )
    finally:
        if not pre_existing:
            dist_file.unlink(missing_ok=True)


@pytest.mark.skipif(
    importlib.util.find_spec('redis') is None,
    reason='requires the optional redis package (always in the tests extra)',
)
def test_combined_includes_redis(tmp_path):
    """B7: the vendored single file must inline redis and bind RedisLock.

    The indented ``from .redis import RedisLock`` in ``__init__.py`` used to
    survive verbatim into the combined file, where it always ImportErrored,
    leaving ``RedisLock`` permanently ``None`` even with redis installed.
    """
    output_file = tmp_path / 'combined_redis.py'
    __main__.main(['combine', '--output-file', str(output_file)])

    # Execute the vendored file in a subprocess exactly as a downstream user
    # importing the single file would (no package context).
    script = (
        'import importlib.util;'
        'spec = importlib.util.spec_from_file_location('
        f'"vendored", r"{output_file}");'
        'mod = importlib.util.module_from_spec(spec);'
        'spec.loader.exec_module(mod);'
        'assert mod.RedisLock is not None, "RedisLock is None";'
        'assert callable(mod.lock), "lock is not callable";'
        'print("OK")'
    )
    result = subprocess.run(
        [sys.executable, '-c', script],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    assert 'OK' in result.stdout


def test_combine_failure_preserves_existing_output(
    tmp_path, monkeypatch, caplog
):
    """A decode failure must not destroy a pre-existing output file.

    ``combine`` used to open (and truncate) ``--output-file`` before
    reading ``README.rst``, so a non-ASCII byte in an input destroyed the
    previous build and died with a raw traceback. All inputs are now read
    and assembled first, and the output is written last, so the
    pre-existing file survives and the error names the offending input.
    """
    (tmp_path / 'README.rst').write_bytes(b'caf\xe9 in the readme\n')
    (tmp_path / 'LICENSE').write_text('license text\n', encoding='ascii')

    output_file = tmp_path / 'combined.py'
    sentinel = '# the previous, perfectly good build\n'
    output_file.write_text(sentinel, encoding='ascii')

    monkeypatch.setattr(__main__, 'base_path', tmp_path)

    with (
        caplog.at_level(logging.ERROR, logger='portalocker.__main__'),
        pytest.raises(UnicodeDecodeError),
    ):
        __main__.main(['combine', '--output-file', str(output_file)])

    # The pre-existing output file is untouched.
    assert output_file.read_text(encoding='ascii') == sentinel
    # The logged error names the offending file and shows a snippet.
    assert 'README.rst' in caplog.text
    assert 'Snippet' in caplog.text


def test_combine_missing_input_exits_with_clear_error(
    tmp_path, monkeypatch, caplog
):
    """A missing README/LICENSE must name the file and exit nonzero.

    It used to escape as a raw ``FileNotFoundError`` traceback. The
    pre-existing output file must survive, as with decode failures.
    """
    # No README.rst in the doctored tree at all.
    (tmp_path / 'LICENSE').write_text('license text\n', encoding='ascii')

    output_file = tmp_path / 'combined.py'
    sentinel = '# the previous, perfectly good build\n'
    output_file.write_text(sentinel, encoding='ascii')

    monkeypatch.setattr(__main__, 'base_path', tmp_path)

    with (
        caplog.at_level(logging.ERROR, logger='portalocker.__main__'),
        pytest.raises(SystemExit) as exc_info,
    ):
        __main__.main(['combine', '--output-file', str(output_file)])

    assert exc_info.value.code == 1
    assert 'README.rst' in caplog.text
    assert 'not found' in caplog.text
    assert output_file.read_text(encoding='ascii') == sentinel


def test_combine_emits_type_checking_block_verbatim(tmp_path):
    """The bundler must emit ``if TYPE_CHECKING:`` blocks verbatim rather
    than inlining their relative imports (which would duplicate a module or
    break the runtime guard the else-branch relies on).

    Exercised directly through ``_read_file`` with a synthetic module so the
    behaviour is covered regardless of whether any shipped module currently
    uses a ``TYPE_CHECKING`` guard.
    """
    module = tmp_path / 'synthetic.py'
    module.write_text(
        'import typing\n'
        'if typing.TYPE_CHECKING:\n'
        '    from .redis import RedisLock\n'
        '\n'
        'value = 1\n',
        encoding='ascii',
    )

    output = ''.join(__main__._read_file(module, set()))

    # The guarded relative import is emitted as-is, not inlined.
    assert 'from .redis import RedisLock' in output
    # ... so redis.py's contents are not pulled in.
    assert 'class RedisLock' not in output
    # The dedented line after the block resumes normal handling.
    assert 'value = 1' in output


def test_combine_without_ruff_logs_and_still_runs(
    tmp_path, monkeypatch, caplog
):
    """A missing ``ruff`` binary is reported, not fatal.

    The combine step shells out to ``ruff`` purely to prettify the
    generated file. On a machine without ruff on ``PATH`` that raises
    ``FileNotFoundError``; combine must log the skip and still smoke-run
    the combined file with the current interpreter.
    """
    calls: list[list[str]] = []

    def fake_run(cmd, *args, **kwargs):
        if cmd[0] == 'ruff':
            raise FileNotFoundError(cmd[0])
        calls.append(list(cmd))
        return subprocess.CompletedProcess(cmd, 0)

    monkeypatch.setattr(subprocess, 'run', fake_run)
    output_file = tmp_path / 'combined_no_ruff.py'

    with caplog.at_level(logging.WARNING, logger='portalocker.__main__'):
        __main__.main(['combine', '--output-file', str(output_file)])

    assert 'Ruff is not installed' in caplog.text
    # The smoke run of the combined file still happened.
    assert [sys.executable, str(output_file)] in calls
